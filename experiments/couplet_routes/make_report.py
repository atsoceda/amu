#!/usr/bin/env python3
"""Regenerate results/report.md for the couplet route experiments from committed JSON.

Run after any new result lands:  python experiments/couplet_routes/make_report.py
Numbers are read from results/<model>/*_summary.json and *_rows.json; the prose
states the motivation, the low-level reading of each table, and the caveats.
"""
from __future__ import annotations

import json
import statistics as st
from pathlib import Path

EXP = Path(__file__).resolve().parent
R = EXP / "results"
MODELS = ["Qwen3-1.7B", "Qwen3-4B", "Qwen3-8B", "Qwen3-14B"]


def load(m, name):
    p = R / m / name
    return json.loads(p.read_text()) if p.exists() else None


def ci(v):
    return "--" if not v else f"{v['mean']:+.1f} [{v['lo']:.1f}, {v['hi']:.1f}]"


def relay_share(rows):
    xs = [x["d_relay"] / x["d_persistence_p0"] for x in rows or [] if "d_relay" in x and abs(x["d_persistence_p0"]) > 1]
    return f"{st.median(xs):.0%}" if xs else "--"


def tail(rows):
    xs = [x for x in rows or [] if "d_relay" in x and abs(x["d_persistence_p0"]) > 1]
    if not xs:
        return "--"
    return f"{sum(x['d_relay'] / x['d_persistence_p0'] > 0.3 for x in xs)}/{len(xs)}"


def main() -> None:
    have = [m for m in MODELS if (R / m / "step34_summary.json").exists()]
    L = ["# Couplet routes: report", "",
         "_Generated by `make_report.py` from the committed JSON in `results/`. Design and commands: `../README.md`. "
         "Terms: `docs/glossary/route-accounting-glossary.html`._", "",
         "## Motivation", "",
         "Rhyming couplets are the flagship example of apparent latent planning (Lindsey et al. 2025; Hanna & Ameisen "
         "2026): the rhyme word of line 2 seems to be chosen in advance, at the end of line 1. The question here is "
         "how that choice reaches the end of line 2, about 16 positions later: by **emission** (through the line-2 "
         "words the model writes), by **direct retrieval** (the rhyme position reads the end of line 1 back), or by "
         "**relay** (carried forward privately through the positions in between). Relay is the novel possibility; "
         "retrieval and emission are the conservative ones.", "",
         "## What was measured", "",
         "Hanna & Ameisen's 100-couplet steering subset per model, their prompt, their anchor (the last word of line 1) "
         "and their donor pairing (a couplet with a different rhyme). The edit places the donor's anchor state at the "
         "anchor (all layers, text unchanged; **state edit**) or applies the authors' rhyme-feature steering "
         "(**feature steering**). Outcome: rhyme preference, the log-probability mass on donor rhymes minus mass on "
         "original rhymes, at the first token of line 2's last word. Persistence is measured with line 2's words fixed "
         "and split by attention path; the paths must add up (additivity gap).", "",
         "## Main result: route split under the state edit", "",
         "| | " + " | ".join(have) + " |", "|---|" + "---|" * len(have)]
    s2 = {m: load(m, "step2_summary.json") for m in have}
    s34 = {m: load(m, "step34_summary.json") for m in have}
    rows = {m: load(m, "step34_rows.json") for m in have}
    nul = {m: load(m, "step34_summary_same_rhyme.json") for m in have}
    table = [
        ("Line 2 rhymes with original: off -> on; with donor: on",
         lambda m: f"{s2[m]['off_rhymes_orig']:.0%} -> {s2[m]['on_rhymes_orig']:.0%}; {s2[m]['on_rhymes_donor']:.0%}"),
        ("Total effect", lambda m: ci(s34[m]["all"]["d_total"])),
        ("Emission (edited line-2 words, edit off)", lambda m: ci(s34[m]["all"]["d_emission"])),
        ("Persistence, original line-2 words", lambda m: ci(s34[m]["all"]["d_persistence_p0"])),
        ("  Direct retrieval", lambda m: ci(s34[m]["all"]["d_retrieval"])),
        ("  Relay", lambda m: ci(s34[m]["all"]["d_relay"])),
        ("  Additivity gap", lambda m: ci(s34[m]["additivity_gap_p0"])),
        ("Median relay share of persistence (per couplet)", lambda m: relay_share(rows[m])),
        ("Couplets with relay share above 30%", lambda m: tail(rows[m])),
        ("Same-rhyme null: persistence", lambda m: ci(nul[m]["all"]["d_persistence_p0"]) if nul[m] else "--"),
    ]
    for label, fn in table:
        L.append(f"| {label} | " + " | ".join(fn(m) for m in have) + " |")
    L += ["", "**Reading.** Most of the edit's effect on the rhyme persists when line 2's words are held fixed, so it is "
          "not carried by the words the model writes. Of that persistence, direct retrieval of the anchor accounts for "
          "most of it at every size (about 82-96%); relay is small but above zero. Relay grows in absolute size with "
          "the whole effect, and its median share rises modestly with scale (see the table); whether that trend continues "
          "is the open scale question. At the largest sizes the paths stop adding up exactly (a small positive additivity "
          "gap), a sign that retrieval and relay partly carry the same information. The same-rhyme null shows that the rhyme-"
          "preference measure tracks rhyme information rather than the edit's general disruption. A small tail of "
          "couplets has a large relay share; it is not yet explained.", ""]
    st6 = {m: load(m, "step6_summary.json") for m in have}
    s6 = [m for m in have if st6[m]]
    if s6:
        L += ["## Robustness: route split under the authors' feature steering", "",
              "| | " + " | ".join(s6) + " |", "|---|" + "---|" * len(s6)]
        for label, key in [("Steered line 2 rhymes with donor (ours)", "on_rhymes_donor"),
                           ("Same, from the authors' released generations", "authors_steered_rhymes_donor")]:
            L.append(f"| {label} | " + " | ".join(f"{st6[m][key]:.0%}" for m in s6) + " |")
        for label, key in [("Total", "d_total"), ("Emission", "d_emission"), ("Persistence, original words", "d_persistence_p0"),
                           ("  Direct retrieval", "d_retrieval"), ("  Relay", "d_relay")]:
            L.append(f"| {label} | " + " | ".join(ci(st6[m]["routes"][key]) for m in s6) + " |")
        L.append(f"| Additivity gap | " + " | ".join(ci(st6[m]["additivity_gap_p0"]) for m in s6) + " |")
        L += ["", "**Reading.** The milder, published intervention changes the rhyme less often at small sizes (as the "
              "authors report), but the route split has the same direction: persistence is mostly direct retrieval, "
              "relay small. This addresses the concern that the all-layer state edit is too disruptive.", ""]
    an = {m: load(m, "anchor_specificity_summary.json") for m in have}
    sa = [m for m in have if an[m]]
    if sa:
        names = {"A": "A: last word of line 1 (anchor)", "E": "E: end of user turn", "C": "C: punctuation after anchor",
                 "M": "M: middle word of line 1", "F": "F: first word of line 1"}
        L += ["## Anchor specificity: where can rhyme information be retrieved from?", "",
              "Persistence when the donor's anchor state is placed at other positions (original line-2 words fixed):", "",
              "| Position | " + " | ".join(sa) + " |", "|---|" + "---|" * len(sa)]
        for k in "AECMF":
            L.append(f"| {names[k]} | " + " | ".join(ci(an[m]["by_position"][k]["persistence"]) for m in sa) + " |")
        L.append(f"| Relay, range across positions | " + " | ".join(
            f"{min(an[m]['by_position'][k]['relay']['mean'] for k in 'AECMF'):+.1f} to {max(an[m]['by_position'][k]['relay']['mean'] for k in 'AECMF'):+.1f}"
            for m in sa) + " |")
        L += ["", "**Reading.** The prediction that only the anchor is retrieved is partly supported: the anchor is about "
              "2-3.5x more effective than any other position, but information at other line-1 positions is still "
              "partly retrieved. Relay stays small whichever position holds the information.", ""]
    L += ["## Converging evidence from the authors' released results", "",
          "Blocking the heads that read the line-1 anchor near the end of line 2 leaves line 2 rhyming in 30% / 20% / "
          "13% / 32% of couplets at 1.7B / 4B / 8B / 14B (all rhymed before): direct retrieval is necessary up to 14B.", "",
          "## Caveats", "",
          "- The all-layer state edit is disruptive (with a same-rhyme donor, rhyming falls to 35-51%); behavioural "
          "rhyme rates mix steering and disruption. The route split concerns rhyme-specific information and is "
          "checked against the feature-steering intervention.",
          "- Rhyme preference counts single-token rhyme words only (Datamuse `rel_rhy`).",
          "- One model family (Qwen3) and one task; 100 couplets per size.",
          "- Unedited generations match the authors' released text exactly on 43-60% of couplets (numerics and "
          "generation path); rhyme behaviour is intact.", "",
          "## Place in the thesis", "",
          "Supports **retrieval over relay** for the flagship planning example: a plan present at a visible word is "
          "looked up where it is needed, not carried. Open: whether relay appears when the information to carry is "
          "derived rather than visible (planned derived-value task), whether the relay-heavy tail has an explanation, "
          "and the 14B point.", ""]
    (R / "report.md").write_text("\n".join(L) + "\n")
    print((R / "report.md").read_text())


if __name__ == "__main__":
    main()
