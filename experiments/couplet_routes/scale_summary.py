#!/usr/bin/env python3
"""Cross-model synthesis: where the rhyme plan is carried, by family, size and format.

Reads results/<model>/{step34,relay_positions,relay_necessity}_summary.json for every
run present and writes results/scale_summary.md (table) and results/scale_summary.png
(figure; hollow markers in the boundary panel are necessity). Quantities are shares of persistence (original line-2 words), which makes
families with different log-probability scales comparable: retrieval, relay (all
in-between positions), boundary (prompt tail after line 1), late (last 3 positions
before the rhyme word), early line 2, and boundary necessity where measured.
"""
from __future__ import annotations

import json
from pathlib import Path

EXP = Path(__file__).resolve().parent
R = EXP / "results"
RUNS = [  # (label, family, format, size in B, run directory)
    ("Qwen3-1.7B", "Qwen3", "chat", 1.7, "Qwen3-1.7B"), ("Qwen3-4B", "Qwen3", "chat", 4, "Qwen3-4B"),
    ("Qwen3-8B", "Qwen3", "chat", 8, "Qwen3-8B"), ("Qwen3-14B", "Qwen3", "chat", 14, "Qwen3-14B"),
    ("Qwen3-32B", "Qwen3", "chat", 32, "Qwen3-32B"),
    ("Qwen3-1.7B", "Qwen3", "plain", 1.7, "Qwen3-1.7B-plain"), ("Qwen3-4B", "Qwen3", "plain", 4, "Qwen3-4B-plain"),
    ("Qwen3-8B", "Qwen3", "plain", 8, "Qwen3-8B-plain"), ("Qwen3-14B", "Qwen3", "plain", 14, "Qwen3-14B-plain"),
    ("Qwen3-32B", "Qwen3", "plain", 32, "Qwen3-32B-plain"),
    ("Qwen3-8B-Base", "Qwen3 base", "plain", 8, "Qwen3-8B-Base-plain"),
    ("Qwen3-14B-Base", "Qwen3 base", "plain", 14, "Qwen3-14B-Base-plain"),
    ("Gemma3-1B", "Gemma3", "chat", 1, "gemma-3-1b-it"), ("Gemma3-4B", "Gemma3", "chat", 4, "gemma-3-4b-it"),
    ("Gemma3-12B", "Gemma3", "chat", 12, "gemma-3-12b-it"), ("Gemma3-27B", "Gemma3", "chat", 27, "gemma-3-27b-it"),
    ("Gemma3-1B", "Gemma3", "plain", 1, "gemma-3-1b-it-plain"), ("Gemma3-4B", "Gemma3", "plain", 4, "gemma-3-4b-it-plain"),
    ("Gemma3-12B", "Gemma3", "plain", 12, "gemma-3-12b-it-plain"), ("Gemma3-27B", "Gemma3", "plain", 27, "gemma-3-27b-it-plain"),
    ("Gemma3-12B-PT", "Gemma3 base", "plain", 12, "gemma-3-12b-pt-plain"),
    ("Gemma3-27B-PT", "Gemma3 base", "plain", 27, "gemma-3-27b-pt-plain"),
]


def load(d, name):
    p = R / d / name
    return json.loads(p.read_text()) if p.exists() else None


def main() -> None:
    rows = []
    for label, fam, fmt, size, d in RUNS:
        s34, pos, nec = load(d, "step34_summary.json"), load(d, "relay_positions_summary.json"), load(d, "relay_necessity_summary.json")
        if not s34 or not pos:
            continue
        pers = pos["all"]["d_persistence_p0"]["mean"]
        sh = lambda k: pos["all"][k]["mean"] / pers  # noqa: E731
        rows.append({"label": label, "family": fam, "format": fmt, "size": size,
                     "persistence": pers, "retrieval": s34["all"]["d_retrieval"]["mean"] / pers,
                     "relay": sh("d_relay_all"), "late": sh("d_relay_late"), "boundary": sh("d_relay_tail"),
                     "early": sh("d_relay_early"), "gap": s34["additivity_gap_p0"]["mean"] / pers,
                     "boundary_necessity": nec["all"]["necessity_tail"]["mean"] / nec["all"]["d_persistence_p0"]["mean"] if nec else None})
    L = ["# Where the rhyme plan is carried: cross-model summary", "",
         "_Generated by `scale_summary.py`. Shares of persistence (original line-2 words); sufficiency measures "
         "(the group alone given its edited-run state), plus boundary necessity where measured (reset the boundary "
         "with the anchor edited). Chat = the authors' chat prompt; plain = Ma & Rui's `A rhyming couplet:` prompt._", "",
         "| Model | Format | Persistence | Retrieval | Relay | Late | Boundary | Early line 2 | Additivity gap | Boundary necessity |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    pc = lambda v: "--" if v is None else f"{100 * v:.0f}%"  # noqa: E731
    for r in rows:
        L.append(f"| {r['label']} | {r['format']} | {r['persistence']:+.1f} | {pc(r['retrieval'])} | {pc(r['relay'])} | "
                 f"{pc(r['late'])} | {pc(r['boundary'])} | {pc(r['early'])} | {pc(r['gap'])} | {pc(r['boundary_necessity'])} |")
    (R / "scale_summary.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.8), sharey=True)
    styles = {("Qwen3", "chat"): ("C0", "o", "-"), ("Qwen3", "plain"): ("C0", "s", "--"),
              ("Gemma3", "chat"): ("C3", "o", "-"), ("Gemma3", "plain"): ("C3", "s", "--"),
              ("Qwen3 base", "plain"): ("C0", "^", ":"), ("Gemma3 base", "plain"): ("C3", "^", ":")}
    for ax, key, title in zip(axes, ("boundary", "late", "early"),
                              ("Boundary (tokens after line 1)", "Late (last 3 before rhyme word)", "Early line 2")):
        for (fam, fmt), (c, mk, ls) in styles.items():
            pts = sorted((r["size"], r[key]) for r in rows if r["family"] == fam and r["format"] == fmt)
            if pts:
                ax.plot([p[0] for p in pts], [100 * p[1] for p in pts], color=c, marker=mk, ls=ls, label=f"{fam}, {fmt}")
            if key == "boundary":
                nec = sorted((r["size"], r["boundary_necessity"]) for r in rows
                             if r["family"] == fam and r["format"] == fmt and r["boundary_necessity"] is not None)
                if nec:
                    ax.plot([p[0] for p in nec], [100 * p[1] for p in nec], color=c, marker=mk, ls="none",
                            mfc="none", ms=9, mew=1.5, label=f"{fam}, {fmt}: necessity")
        ax.set_xscale("log"); ax.set_title(title, fontsize=10); ax.set_xlabel("parameters (B)"); ax.axhline(0, color="k", lw=0.5)
    axes[0].set_ylabel("relay, % of persistence")
    axes[0].legend(fontsize=6, loc="upper left")
    fig.tight_layout()
    fig.savefig(R / "scale_summary.png", dpi=150)


if __name__ == "__main__":
    main()
